`ifndef UART_GENERATOR_SV
`define UART_GENERATOR_SV
class generator;
    mailbox #(transaction) mbx; // Send generated bytes to the driver.
    int count = 500;            // Configure the number of accepted bytes here; environment uses this value.

    function new(mailbox #(transaction) mbx);
        this.mbx = mbx; // Use the mailbox created by the environment.
    endfunction

    task run();
        transaction tr;
        repeat (count) begin
            tr = new();                      // Allocate a separate object for each byte.
            if (!tr.randomize())             // Randomize all eight data bits.
                $fatal(1, "[GEN] Byte randomization failed");
            mbx.put(tr);                     // Keep the byte queued until the driver takes it.
        end
    endtask
endclass
`endif
